const LocaleContext = createContext(null);

export function I18nProvider({ children }) {
  const [locale, setLocale] = useState(() => localStorage.getItem('openbox3d-locale') || 'zh');
  useEffect(() => {
    localStorage.setItem('openbox3d-locale', locale);
    document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN';
    document.title = locale === 'en' ? 'OpenBox3D Workbench' : '苏哇工作台 · OpenBox3D';
  }, [locale]);
  const value = useMemo(() => ({ locale, setLocale }), [locale]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useI18n() {
  const context = useContext(LocaleContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}

function translateNode(node) {
  if (typeof node === 'string') return translations[node] || node;
  if (!React.isValidElement(node)) return node;
  const props = {};
  for (const [key, value] of Object.entries(node.props)) {
    if (key === 'children') props.children = React.Children.map(value, translateNode);
    else if (['title', 'aria-label', 'placeholder', 'label', 'k', 'v'].includes(key) && typeof value === 'string') props[key] = translations[value] || value;
  }
  return React.cloneElement(node, props);
}

export function translateText(text, locale) {
  return locale === 'en' ? translations[text] || text : text;
}

export function Translate({ children }) {
  const { locale } = useI18n();
  if (locale !== 'en') return children;
  return React.Children.map(children, translateNode);
}
